import { expect, test, type Page } from '@playwright/test'

async function openRecord(page: Page) {
  await page.getByRole('button', { name: '카페인 추가', exact: true }).click()
  await page.getByRole('button', { name: /아메리카노\s*150\s*mg/ }).click()
}

test('records, reloads, edits and clears an optional memo', async ({ page }, testInfo) => {
  await page.goto('/')
  await openRecord(page)
  await page.getByRole('textbox', { name: '메모', exact: true }).fill('점심 후 한 잔\n진하게 마셨어요')
  await expect(page.locator('.intake-note-count')).toHaveText('17/100')
  await page.screenshot({ path: `test-results/${testInfo.project.name}-intake-note.png` })
  await page.getByRole('button', { name: '기록 저장', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByRole('navigation').getByRole('button', { name: '기록', exact: true }).click()
  await expect(page.locator('.entry-note')).toHaveText('점심 후 한 잔\n진하게 마셨어요')
  await page.reload()
  await expect(page.locator('.entry-note')).toHaveText('점심 후 한 잔\n진하게 마셨어요')
  await page.getByRole('button', { name: '아메리카노 기록 수정' }).click()
  await expect(page.getByRole('textbox', { name: '메모', exact: true })).toHaveValue('점심 후 한 잔\n진하게 마셨어요')
  await page.getByLabel('카페인량 (mg)').fill('175')
  await page.getByRole('button', { name: '수정 저장' }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(page.locator('.entry-note')).toHaveText('점심 후 한 잔\n진하게 마셨어요')
  await page.getByRole('button', { name: '아메리카노 기록 수정' }).click()
  await page.getByRole('textbox', { name: '메모', exact: true }).fill('  다음엔 연하게  ')
  await page.getByRole('button', { name: '수정 저장' }).click()
  await expect(page.locator('.entry-note')).toHaveText('다음엔 연하게')
  await page.reload()
  await expect(page.locator('.entry-note')).toHaveText('다음엔 연하게')
  await page.getByRole('button', { name: '아메리카노 기록 수정' }).click()
  await page.getByRole('textbox', { name: '메모', exact: true }).fill('')
  await page.getByRole('button', { name: '수정 저장' }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(page.locator('.entry-note')).toHaveCount(0)
  await page.reload()
  await expect(page.locator('.entry-note')).toHaveCount(0)
  await expect(page.getByTestId('daily-total')).toHaveText('175')
})

test('limits a long pasted memo and does not carry it into another record', async ({ page }) => {
  await page.goto('/')
  await openRecord(page)
  await page.getByRole('textbox', { name: '메모', exact: true }).fill('가'.repeat(99) + '😀끝')
  await expect(page.getByRole('textbox', { name: '메모', exact: true })).toHaveValue('가'.repeat(99) + '😀')
  await expect(page.locator('.intake-note-count')).toHaveText('100/100')
  await page.getByRole('button', { name: '기록 저장', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await openRecord(page)
  await expect(page.getByRole('textbox', { name: '메모', exact: true })).toHaveValue('')
  await page.getByRole('button', { name: '기록 저장', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByRole('navigation').getByRole('button', { name: '기록', exact: true }).click()
  await expect(page.locator('.history-entry')).toHaveCount(2)
  await expect(page.locator('.entry-note')).toHaveCount(1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
})

test('a past-date slow intake preserves its memo through the time picker', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-09T10:00:00+09:00') })
  await page.goto('/history')
  await page.getByRole('button', { name: /^2026년 10월 3일/ }).click()
  await openRecord(page)
  await page.getByRole('textbox', { name: '메모', exact: true }).fill('이동하면서 천천히 마셨어요')
  await page.getByRole('button', { name: '천천히 마시기', exact: true }).click()
  await page.getByRole('button', { name: '마시기 시작한 시각', exact: true }).click()
  await page.goBack()
  await expect(page.getByRole('textbox', { name: '메모', exact: true })).toHaveValue('이동하면서 천천히 마셨어요')
  await page.getByRole('button', { name: '기록 저장', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(page.locator('.entry-note')).toHaveText('이동하면서 천천히 마셨어요')
  await page.reload()
  await page.getByRole('button', { name: /^2026년 10월 3일/ }).click()
  await expect(page.locator('.entry-note')).toHaveText('이동하면서 천천히 마셨어요')
  await expect(page.getByRole('button', { name: /^2026년 10월 3일/ })).toHaveAttribute('aria-pressed', 'true')
})
